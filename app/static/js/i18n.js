function getLang() {
  try {
    const stored = localStorage.getItem("gmc_lang");
    if (stored === "de" || stored === "en") return stored;
  } catch (e) {}
  const nav = (navigator.language || "").toLowerCase();
  if (nav.startsWith("en")) return "en";
  if (nav.startsWith("de")) return "de";
  return window.__INITIAL_LANG__ || "de";
}

function setLang(lang) {
  try {
    localStorage.setItem("gmc_lang", lang);
  } catch (e) {}
  applyLang(lang);
}

function tUI(key) {
  const entry = I18N[key];
  if (!entry) return key;
  return entry[getLang()] || entry.de || key;
}

function applyLang(lang) {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const entry = I18N[el.getAttribute("data-i18n")];
    if (entry) el.textContent = entry[lang] || entry.de;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const entry = I18N[el.getAttribute("data-i18n-html")];
    if (entry) el.innerHTML = entry[lang] || entry.de;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const entry = I18N[el.getAttribute("data-i18n-placeholder")];
    if (entry) el.placeholder = entry[lang] || entry.de;
  });
  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang-btn") === lang);
  });
  const titleEntry = I18N["meta.title"];
  if (titleEntry) document.title = titleEntry[lang] || titleEntry.de;
}
